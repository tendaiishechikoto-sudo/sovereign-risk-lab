function makeChartSVG(container, { width = 640, height = 320, margin = { top: 16, right: 20, bottom: 32, left: 48 } }) {
  container.innerHTML = "";
  const svg = svgEl("svg", { viewBox: `0 0 ${width} ${height}`, role: "img" });
  container.appendChild(svg);
  return { svg, width, height, margin };
}

function scaleLinear(domain, range) {
  const [d0, d1] = domain, [r0, r1] = range;
  const span = d1 - d0 || 1;
  return (v) => r0 + ((v - d0) / span) * (r1 - r0);
}

function scaleLog(domain, range) {
  const lo = Math.max(domain[0], 1e-6);
  const hi = Math.max(domain[1], lo * 10);
  const logLo = Math.log10(lo), logHi = Math.log10(hi);
  const [r0, r1] = range;
  const span = (logHi - logLo) || 1;
  return (v) => {
    const vv = Math.max(v, lo);
    return r0 + ((Math.log10(vv) - logLo) / span) * (r1 - r0);
  };
}

function niceLogTicks(domain) {
  const lo = Math.max(domain[0], 1e-6);
  const hi = Math.max(domain[1], lo * 10);
  const startExp = Math.floor(Math.log10(lo));
  const endExp = Math.ceil(Math.log10(hi));
  const ticks = [];
  for (let e = startExp; e <= endExp; e++) ticks.push(Math.pow(10, e));
  return ticks;
}

function niceLinearTicks(domain, count = 4) {
  const [lo, hi] = domain;
  const span = hi - lo || 1;
  const step = span / count;
  const ticks = [];
  for (let i = 0; i <= count; i++) ticks.push(lo + step * i);
  return ticks;
}

let tooltipEl = null;
function getTooltip() {
  if (!tooltipEl) {
    tooltipEl = el("div", { class: "viz-tooltip" });
    tooltipEl.style.display = "none";
    document.body.appendChild(tooltipEl);
  }
  return tooltipEl;
}

function showTooltip(x, y, titleText, rows) {
  const tip = getTooltip();
  tip.innerHTML = "";
  tip.appendChild(el("div", { class: "tt-title" }, titleText));
  for (const row of rows) {
    const keyWrap = el("span", { class: "tt-key" }, [
      el("span", { class: "tt-swatch", style: `background:${row.color}` }),
      document.createTextNode(row.label),
    ]);
    keyWrap.style.setProperty("--swatch-color", row.color);
    const swatch = keyWrap.querySelector(".tt-swatch");
    swatch.style.background = row.color;
    tip.appendChild(el("div", { class: "tt-row" }, [
      keyWrap,
      el("span", { class: "tt-value" }, row.value),
    ]));
  }
  tip.style.display = "block";
  tip.style.left = `${x + 14}px`;
  tip.style.top = `${y + 14}px`;
}

function hideTooltip() {
  if (tooltipEl) tooltipEl.style.display = "none";
}

