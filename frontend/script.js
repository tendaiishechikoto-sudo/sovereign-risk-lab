async function loadJSON(filename) {
  const resp = await fetch(DATA_DIR + filename, { cache: "no-store" });
  if (!resp.ok) {
    throw new Error(`${filename}: HTTP ${resp.status}`);
  }
  return resp.json();
}

async function loadAllData() {
  const files = [
    "meta.json",
    "panel.json",
    "latest_snapshot.json",
    "devaluation_events.json",
    "policy_rate_decisions.json",
    "imf_program_status.json",
  ];
  const results = {};
  const missing = [];
  for (const f of files) {
    try {
      results[f.replace(".json", "")] = await loadJSON(f);
    } catch (err) {
      missing.push(f);
    }
  }
  return { data: results, missing };
}

