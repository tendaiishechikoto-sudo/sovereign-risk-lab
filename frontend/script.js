function renderLineChart(containerId, { series, yLabel, useLogScale = false, valueFormatter = (v) => fmtNum(v) }) {
  const container = document.getElementById(containerId);
  const { svg, width, height, margin } = makeChartSVG(container, {
    width: 640, height: 300, margin: { top: 16, right: 56, bottom: 32, left: 48 },
  });
  const plotW = width - margin.left - margin.right;
  const plotH = height - margin.top - margin.bottom;

  const allYears = [...new Set(series.flatMap((s) => s.points.map((p) => p.year)))].sort((a, b) => a - b);
  const allValues = series.flatMap((s) => s.points.map((p) => p.value)).filter((v) => v !== null && !Number.isNaN(v));

  if (allYears.length === 0 || allValues.length === 0) {
    container.appendChild(el("p", { class: "section-note" }, "No data available."));
    return;
  }

  const xScale = scaleLinear([allYears[0], allYears[allYears.length - 1]], [margin.left, margin.left + plotW]);
  const yDomain = useLogScale
    ? [Math.max(Math.min(...allValues), 1e-3), Math.max(...allValues)]
    : [Math.min(0, Math.min(...allValues)), Math.max(...allValues) * 1.1];
  const yScale = useLogScale ? scaleLog(yDomain, [margin.top + plotH, margin.top]) : scaleLinear(yDomain, [margin.top + plotH, margin.top]);
  const yTicks = useLogScale ? niceLogTicks(yDomain) : niceLinearTicks(yDomain);

  const plot = svgEl("g", {});
  svg.appendChild(plot);

  // Gridlines + y-axis labels
  for (const t of yTicks) {
    const y = yScale(t);
    plot.appendChild(svgEl("line", { class: "gridline", x1: margin.left, x2: margin.left + plotW, y1: y, y2: y }));
    const label = svgEl("text", { class: "axis-label", x: margin.left - 8, y: y + 4, "text-anchor": "end" });
    label.textContent = valueFormatter(t);
    plot.appendChild(label);
  }
  // X axis (years) — thin out ticks if many years
  const xTickEvery = allYears.length > 8 ? 2 : 1;
  allYears.forEach((yr, i) => {
    if (i % xTickEvery !== 0 && i !== allYears.length - 1) return;
    const x = xScale(yr);
    const label = svgEl("text", { class: "axis-label", x, y: margin.top + plotH + 18, "text-anchor": "middle" });
    label.textContent = String(yr);
    plot.appendChild(label);
  });
  plot.appendChild(svgEl("line", { class: "axis-line", x1: margin.left, x2: margin.left + plotW, y1: margin.top + plotH, y2: margin.top + plotH }));

  // Lines + end markers + end labels
  for (const s of series) {
    const pts = s.points.filter((p) => p.value !== null && !Number.isNaN(p.value)).sort((a, b) => a.year - b.year);
    if (pts.length === 0) continue;
    const d = pts.map((p, i) => `${i === 0 ? "M" : "L"} ${xScale(p.year)} ${yScale(p.value)}`).join(" ");
    plot.appendChild(svgEl("path", { d, fill: "none", stroke: s.color, "stroke-width": 2, "stroke-linejoin": "round", "stroke-linecap": "round" }));

    const last = pts[pts.length - 1];
    const cx = xScale(last.year), cy = yScale(last.value);
    plot.appendChild(svgEl("circle", { cx, cy, r: 4, fill: s.color, stroke: "var(--surface-1)", "stroke-width": 2 }));
    const endLabel = svgEl("text", { class: "axis-label", x: cx + 6, y: cy + 4, fill: s.color, "font-weight": 600 });
    endLabel.textContent = s.iso3 || s.name;
    plot.appendChild(endLabel);

    // Invisible hover targets on each point
    pts.forEach((p) => {
      const hit = svgEl("circle", { cx: xScale(p.year), cy: yScale(p.value), r: 12, fill: "transparent" });
      hit.style.cursor = "pointer";
      hit.addEventListener("pointermove", (evt) => {
        showTooltip(evt.pageX, evt.pageY, `${p.year}`, [{ color: s.color, label: s.name, value: valueFormatter(p.value) }]);
      });
      hit.addEventListener("pointerleave", hideTooltip);
      plot.appendChild(hit);
    });
  }

  renderLegend(container, series);
}

function renderLegend(container, series) {
  if (series.length < 2) return;
  const legend = el("div", { class: "chart-legend" });
  for (const s of series) {
    legend.appendChild(el("span", { class: "legend-item" }, [
      el("span", { class: "legend-swatch", style: `background:${s.color}` }),
      s.name,
    ]));
  }
  container.appendChild(legend);
}

// ---------------------------------------------------------------------
// Horizontal bar chart (CSRI composite)
// ---------------------------------------------------------------------

function renderBarChart(containerId, { bars, valueFormatter = (v) => fmtNum(v), domain = null }) {
  const container = document.getElementById(containerId);
  const rowH = 56;
  const margin = { top: 12, right: 60, bottom: 12, left: 100 };
  const width = 640;
  const height = margin.top + margin.bottom + bars.length * rowH;
  const { svg } = makeChartSVG(container, { width, height, margin });
  const plotW = width - margin.left - margin.right;

  const values = bars.map((b) => b.value).filter((v) => v !== null && !Number.isNaN(v));
  const dom = domain || [0, Math.max(100, ...values)];
  const xScale = scaleLinear(dom, [0, plotW]);

  bars.forEach((b, i) => {
    const y = margin.top + i * rowH;
    const barH = 24;
    const barY = y + (rowH - barH) / 2;

    const label = svgEl("text", { class: "axis-label", x: margin.left - 10, y: barY + barH / 2 + 4, "text-anchor": "end", "font-weight": 600 });
    label.textContent = b.name;
    svg.appendChild(label);

    svg.appendChild(svgEl("line", {
      class: "gridline", x1: margin.left, x2: margin.left + plotW, y1: barY + barH / 2, y2: barY + barH / 2,
    }));

    if (b.value === null || Number.isNaN(b.value)) {
      const naLabel = svgEl("text", { class: "axis-label", x: margin.left + 8, y: barY + barH / 2 + 4 });
      naLabel.textContent = "No data";
      svg.appendChild(naLabel);
      return;
    }

    const barW = Math.max(2, xScale(b.value) - xScale(dom[0]));
    const barX = margin.left + xScale(dom[0]);
    const rect = svgEl("rect", {
      x: barX, y: barY, width: barW, height: barH, rx: 4, fill: b.color,
    });
    rect.style.cursor = "pointer";
    rect.addEventListener("pointermove", (evt) => {
      showTooltip(evt.pageX, evt.pageY, b.name, [{ color: b.color, label: "CSRI", value: valueFormatter(b.value) }]);
    });
    rect.addEventListener("pointerleave", hideTooltip);
    svg.appendChild(rect);

    const valueLabel = svgEl("text", {
      class: "axis-label", x: barX + barW + 8, y: barY + barH / 2 + 4, "font-weight": 600,
    });
    valueLabel.setAttribute("fill", "var(--text-primary)");
    valueLabel.textContent = valueFormatter(b.value);
    svg.appendChild(valueLabel);
  });
}

// ---------------------------------------------------------------------
// Table toggles (accessibility: every chart has a table view)
// ---------------------------------------------------------------------

function buildDataTable(columns, rows) {
  const table = el("table", { class: "data-table" });
  const thead = el("thead", {}, el("tr", {}, columns.map((c) => el("th", { class: c.num ? "num" : "" }, c.label))));
  const tbody = el("tbody", {}, rows.map((r) => el("tr", {}, columns.map((c) => el("td", { class: c.num ? "num" : "" }, c.render(r))))));
  table.appendChild(thead);
  table.appendChild(tbody);
  return table;
}

function wireTableToggle(key) {
  const btn = document.querySelector(`[data-toggle-table="${key}"]`);
  if (!btn) return;
  btn.addEventListener("click", () => {
    const tableEl = document.getElementById(`${key}-table`);
    const chartEl = document.getElementById(`${key}-chart`);
    const showing = !tableEl.hidden;
    tableEl.hidden = showing;
    if (chartEl) chartEl.hidden = !showing;
    btn.setAttribute("aria-expanded", String(!showing));
    btn.textContent = showing ? "View as table" : "View as chart";
  });
}

