function renderKPIRow(snapshot) {
  const row = document.getElementById("kpi-row");
  row.innerHTML = "";
  if (!snapshot) return;
  for (const iso3 of COUNTRY_ORDER) {
    const info = COUNTRIES[iso3];
    const score = snapshot.csri_composite_0_100[iso3];
    const used = snapshot.components_used_per_country[iso3] || [];
    const total = Object.keys(snapshot.weights).length;
    const tile = el("div", { class: "kpi-tile", style: `--tile-accent:${info.color}` }, [
      el("div", { class: "kpi-label" }, [el("span", { class: "kpi-dot" }), info.name]),
      el("div", { class: "kpi-value" }, score === null || Number.isNaN(score) ? "—" : fmtNum(score)),
      el("div", { class: "kpi-sub" }, `Based on ${used.length}/${total} components (see below for exclusions)`),
    ]);
    row.appendChild(tile);
  }
}

function renderCSRIChart(snapshot) {
  if (!snapshot) return;
  const bars = COUNTRY_ORDER
    .map((iso3) => ({ name: COUNTRIES[iso3].name, value: snapshot.csri_composite_0_100[iso3], color: COUNTRIES[iso3].color }))
    .sort((a, b) => (a.value ?? -Infinity) - (b.value ?? -Infinity));
  renderBarChart("csri-chart", { bars, domain: [0, 100] });

  const tableContainer = document.getElementById("csri-table");
  tableContainer.innerHTML = "";
  tableContainer.appendChild(buildDataTable(
    [
      { label: "Country", render: (r) => r.name },
      { label: "CSRI (0-100)", num: true, render: (r) => fmtNum(r.value) },
      { label: "Components used", num: true, render: (r) => `${(snapshot.components_used_per_country[Object.keys(COUNTRIES).find((k) => COUNTRIES[k].name === r.name)] || []).length}/${Object.keys(snapshot.weights).length}` },
    ],
    bars,
  ));
}

function panelSeries(panel, indicatorKey, valueScale = 1) {
  return COUNTRY_ORDER.map((iso3) => ({
    iso3,
    name: COUNTRIES[iso3].name,
    color: COUNTRIES[iso3].color,
    points: panel.filter((r) => r.country_iso3 === iso3).map((r) => ({ year: r.year, value: r[indicatorKey] === null ? null : r[indicatorKey] * valueScale })),
  }));
}

